// v70: conserve e bevande. Salina (sale), macellaio e affumicatoio (conserve), caseificio (formaggio dal latte degli ovili), birrificio (birra dal grano),
// cantina (vino dalla coltura vigna delle fattorie). Le conserve sfamano le case senza cibo fresco, birra e vino rallegrano la taverna, tutto si vende in città.
const Sim=require('../src/sim.js');const S=Sim.S;
let fails=0;const ok=(c,m)=>{console.log((c?'  ok ':'  ERRORE ')+m);if(!c)fails++;};
Sim.init(7,'lake','facile');S.stock.wood=500;S.stock.stone=300;S.stock.planks=20;
Sim.paintDistrict(60,100,125,128,1);Sim.paintDistrict(100,70,130,92,3);Sim.paintDistrict(60,60,90,92,5);Sim.paintDistrict(60,30,100,58,2);Sim.paintDistrict(100,94,125,99,2);
const top=(k,n)=>{S.stock[k]=Math.max(S.stock[k],Math.min(n,Sim.capRes(k)));};
let feed=false;
const hold=()=>{top('wood',300);top('stone',200);if(feed){top('meat',20);top('fish',20);top('grain',30);}};
const run=d=>{for(let i=0;i<d*Sim.DAY/0.2;i++){Sim.step(0.2);if(i%10===0)hold();}};
const B=()=>[...Sim.buildings().values()];
const done=t=>B().filter(b=>b.type===t&&b.state==='done');
const psf=()=>done('sheepfold').filter(b=>!b.owner)[0];
function put1(type,x0,y0){
  for(let r=0;r<70;r+=3)for(let dy=-r;dy<=r;dy+=3)for(let dx=-r;dx<=r;dx+=3){
    if(Math.max(Math.abs(dx),Math.abs(dy))!==r)continue;
    for(const rot of [0,1,2,3]){const res=Sim.place(type,x0+dx,y0+dy,rot);if(res.ok)return res.b;}
  }
  return null;
}
const put=(type,x0,y0)=>put1(type,x0,y0)||[[90,125],[115,80],[75,100],[120,115],[65,115],[95,70],[110,135]].map(o=>put1(type,o[0],o[1])).find(Boolean)||null;
for(const [t,x,y] of [['plaza',90,90],['well',84,96],['church',90,108],['store',96,98],['granary',104,100]])Sim.place(t,x,y,0);
// le sei botteghe si piazzano subito, a mappa ancora libera (più avanti case e boschi occupano lo spazio)
const br=put('brewery',100,112),sm=put('smokehouse',112,104),sf=put('sheepfold',70,70),da=put('dairy',80,84),sl=put('saltworks',118,138),bu=put('butcher',108,112);
run(10);
let farms=done('farm');for(let k=0;k<20&&!farms.length;k++){run(3);farms=done('farm');}
console.log('Abitanti',Sim.villagers().length,'fattorie',farms.length,'granai',done('granary').length);
ok(done('granary').length===1&&done('store').length===1,'Granaio e Magazzino pronti');
console.log('1) costi e albero');
const cs=Sim.costOf('saltworks'),cw=Sim.costOf('winery');
ok(cs.bricks===0&&cs.stone===4+Math.ceil(4*1.5),'salina senza fornace: mattoni in pietra '+JSON.stringify(cs));
ok(cw.bricks===0&&cw.lime===0&&cw.planks===0&&cw.wood===16+2*4&&cw.stone===6+Math.ceil(4*1.5)+Math.ceil(2*1.5),'cantina senza fornace, calcinaio e falegnameria: tutto in legno e pietra '+JSON.stringify(cw));
const by=Object.fromEntries(Sim.PROJ.map(p=>[p.id,p]));
for(const id of ['saltworks','butcher','smokehouse','dairy','brewery','winery'])ok(!!by[id]&&by[id].br==='campi','blueprint nel ramo Campi e cibo: '+id);
ok(by.saltworks.rank===3&&by.saltworks.req.includes('fisher'),'salina: titolo 3, dopo il pescatore');
ok(by.butcher.rank===4&&by.butcher.req.includes('hunter')&&by.butcher.req.includes('saltworks'),'macellaio: titolo 4, dopo cacciatore e salina');
ok(by.smokehouse.rank===4&&by.smokehouse.req.includes('fisher')&&by.smokehouse.req.includes('saltworks'),'affumicatoio: titolo 4, dopo pescatore e salina');
ok(by.dairy.rank===5&&by.dairy.req.includes('sheepfold'),'caseificio: titolo 5, dopo l\'ovile');
ok(by.brewery.rank===5&&by.brewery.req.includes('mill'),'birrificio: titolo 5, dopo il mulino');
ok(by.winery.rank===6&&by.winery.req.includes('brewery'),'cantina: titolo 6, dopo il birrificio');
ok(Sim.PROJ.every(p=>(p.req||[]).every(q=>by[q].rank<=p.rank)),'nessun blueprint dipende da uno di titolo più alto');
console.log('2) salina, macellaio, affumicatoio, birrificio, caseificio');
ok(Sim.place('saltworks',20,20,0).ok===false,'la salina lontano dall\'acqua è rifiutata');
for(const [n,b] of [['ovile',sf],['caseificio',da],['salina',sl],['macellaio',bu],['affumicatoio',sm],['birrificio',br]])ok(!!b,'piazzato: '+n);
feed=true;run(16);
for(const t of ['saltworks','butcher','smokehouse','brewery','dairy'])ok(done(t).length===1&&done(t)[0].workers.length>=1,'completato e con addetto: '+t);
ok(!!psf()&&psf().workers.length>=1,'ovile del giocatore con pastore');
run(12);
console.log('   scorte',JSON.stringify({salt:S.stock.salt,cured:S.stock.cured,cheese:S.stock.cheese,beer:S.stock.beer}),'cicli',JSON.stringify(S.made));
ok((S.made.saltworks|0)>0&&S.stock.salt>0,'sale prodotto: '+S.stock.salt+' ('+(S.made.saltworks|0)+' cicli)');
ok((S.made.butcher|0)>0,'il macellaio ha lavorato: '+(S.made.butcher|0)+' cicli');
ok((S.made.smokehouse|0)>0,'l\'affumicatoio ha lavorato: '+(S.made.smokehouse|0)+' cicli');
ok(S.stock.cured>0,'conserve disponibili: '+S.stock.cured);
ok((S.made.brewery|0)>0&&S.stock.beer>0,'birra prodotta: '+S.stock.beer+' ('+(S.made.brewery|0)+' cicli)');
ok(psf().milk>0||(S.made.dairy|0)>0,'l\'ovile dà latte: '+psf().milk);
ok((S.made.dairy|0)>0&&S.stock.cheese>0,'formaggio fatto: '+S.stock.cheese+' ('+(S.made.dairy|0)+' cicli)');
console.log('3) le conserve si fanno solo con l\'eccedenza');
feed=false;
const WSx=Sim.WS;
S.stock.meat=Sim.MEAT_KEEP+1;S.stock.salt=5;ok(!WSx.butcher.can(done('butcher')[0]),'il macellaio non lavora con la sola riserva fresca');
S.stock.meat=Sim.MEAT_KEEP+2;ok(!!WSx.butcher.can(done('butcher')[0])||S.stock.cured>=Sim.CURED_CAP-3,'con l\'eccedenza il macellaio lavora');
S.stock.fish=Sim.FISH_KEEP+1;S.stock.wood=Math.max(S.stock.wood,30);ok(!WSx.smokehouse.can(done('smokehouse')[0]),'l\'affumicatoio non lavora con la sola riserva fresca');
S.stock.grain=Sim.GRAIN_KEEP+1;ok(!WSx.brewery.can(done('brewery')[0]),'il birrificio non lavora con la sola riserva del mulino');
console.log('4) cantina con la coltura vigna');
const f=farms[0];
ok(Sim.setFarmCrop(f.id,'vine')==='ok'&&f.crop==='vine','coltura vigna scelta');
ok(Sim.sinkOf(f)==='winery','l\'uva va alla cantina');
const wn=put('winery',114,118);ok(!!wn,'cantina piazzata');
feed=true;run(30);
const W=done('winery')[0];
console.log('   cantina inp',JSON.stringify(W&&W.inp),'vino',S.stock.wine,'cicli',S.made.winery);
ok(!!W&&W.workers.length>=1,'vinaio al lavoro');
ok((S.made.winery|0)>0&&S.stock.wine>0,'vino prodotto: '+S.stock.wine+' ('+(S.made.winery|0)+' cicli)');
feed=false;
console.log('5) conserve alle case senza cibo fresco');
const h=done('house')[0];
for(const k of Object.keys(h.goods))if(['veg','eggs','grain','fish','meat','game','bread'].includes(k))h.goods[k]=0;
S.stock.cured=3;S.stock.cheese=2;
ok(Sim._t.eatOne(h,null)===true&&S.stock.cured===2,'la casa mangia una conserva: '+S.stock.cured);
S.stock.cured=0;ok(Sim._t.eatOne(h,null)===true&&S.stock.cheese===1,'poi il formaggio: '+S.stock.cheese);
S.stock.cheese=0;ok(Sim._t.eatOne(h,null)===false,'senza niente resta a stomaco vuoto');
console.log('6) taverna con birra e vino');
const tv=put('tavern',100,104);ok(!!tv,'taverna piazzata');run(14);
const T=done('tavern')[0];ok(!!T&&T.workers.length>=1,'taverna con addetto');
S.stock.wine=3;S.stock.beer=3;T.drink=0;T.drinkT=0;Sim._t.drinkTick();
ok(S.stock.wine===2&&S.stock.beer===3&&T.drink>S.t,'la taverna serve prima il vino: vino '+S.stock.wine);
S.stock.wine=0;T.drink=0;T.drinkT=0;Sim._t.drinkTick();
ok(S.stock.beer===2&&T.drink>S.t,'senza vino serve la birra: birra '+S.stock.beer);
S.stock.beer=0;T.drink=0;T.drinkT=0;Sim._t.drinkTick();ok(!(T.drink>S.t),'senza bevande niente bonus');
console.log('7) commercio e magazzini');
S.stock.wine=25;S.stock.salt=0;
ok(Sim.TOWNS.n.buys.wine>0&&Sim.TOWNS.e.buys.cured>0&&Sim.TOWNS.w.buys.cheese>0&&Sim.TOWNS.s.buys.beer>0,'le città comprano vino, conserve, formaggio, birra');
ok(Sim.TOWNS.n.sells.salt>0&&Sim.TOWNS.e.sells.salt>0,'e vendono sale');
ok(Sim.surplusOf('wine')>0,'vino in eccedenza da vendere: '+Sim.surplusOf('wine'));
ok(Sim.demandOf('salt')>0,'senza sale lo si compra: '+Sim.demandOf('salt'));
const mi=Sim.storeInfo(done('store')[0]),gi=Sim.storeInfo(done('granary')[0]);
ok(mi.keys.includes('salt'),'il Magazzino accoglie il sale');
ok(['cured','cheese','beer','wine'].every(k=>gi.keys.includes(k)),'il Granaio accoglie conserve, formaggio, birra e vino: '+gi.keys.join(','));
console.log('8) salvataggio e vecchi salvataggi');
S.stock.cheese=4;S.stock.salt=7;psf().milk=5;
const dump=JSON.parse(JSON.stringify(Sim.exportState()));
Sim.init(9,'lake');Sim.importState(dump);
ok(S.stock.cheese===4&&S.stock.salt===7&&psf().milk===5,'scorte e latte salvati');
const old=JSON.parse(JSON.stringify(dump));
for(const k of ['salt','cured','cheese','beer','wine'])delete old.S.stock[k];
for(const b of old.buildings)if(b.type==='sheepfold')delete b.milk;
Sim.importState(old);
ok(['salt','cured','cheese','beer','wine'].every(k=>S.stock[k]===0)&&psf().milk===0,'vecchi salvataggi: tutto a zero');
ok(Object.keys(S.stock).every(k=>Number.isFinite(S.stock[k])),'scorte tutte numeriche');
console.log(fails===0?'CONSERVE_OK':'CONSERVE_FAIL ('+fails+')');process.exit(fails===0?0:1);
