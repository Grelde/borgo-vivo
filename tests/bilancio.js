// v80: editto delle tasse, registro settimanale della cassa, conseguenze degli arretrati.
const Sim=require('../src/sim.js');const S=Sim.S;
let fails=0;const ok=(c,m)=>{console.log((c?'  ok ':'  ERRORE ')+m);if(!c)fails++;};
Sim.init(7,'lake');S.stock.wood=500;S.stock.stone=300;
Sim.paintDistrict(60,100,100,124,1);
const run=d=>{for(let i=0;i<d*Sim.DAY/0.5;i++){Sim.step(0.5);if(i%10===0)S.stock.wood=Math.max(S.stock.wood,300);}};
for(const [t,x,y] of [['plaza',90,90],['well',84,96]])Sim.place(t,x,y,0);
run(10);
console.log('1) aliquote');
ok(S.taxRate==='normal'&&[1,2,3,4,5].map(Sim.taxOf).join()==='1,3,5,10,20','normale: 1,3,5,10,20');
Sim.setTaxRate('low');ok([1,2,3,4,5].map(Sim.taxOf).join()==='0,1,2,5,10','bassa: 0,1,2,5,10');
Sim.setTaxRate('high');ok([1,2,3,4,5].map(Sim.taxOf).join()==='2,6,10,20,40','alta: 2,6,10,20,40');
ok(!Sim.setTaxRate('xx').ok&&S.taxRate==='high','aliquota sconosciuta rifiutata');
Sim.setTaxRate('normal');
console.log('2) previsione e registro');
const fc=Sim.taxForecast();ok(fc.weekly>=0&&fc.expect<=fc.weekly,'previsione coerente');
S.ledger={snap:null,rows:[]};run(1);run(8);run(8);
ok(S.ledger.rows.length>=1,'il registro ha righe: '+S.ledger.rows.length);
const r=S.ledger.rows[0];
ok(r&&r.in===r.tax+r.trade&&r.net===r.other+r.in-r.out,'entrate, uscite e saldo tornano');
console.log('3) arretrati e felicità');
const v=Sim.villagers().find(x=>x.home&&Sim.buildings().get(x.home));
const h=Sim.buildings().get(v.home);
S.story=true;S.rank=6;h.owed=0;const j0=Sim.joyOf(v);h.owed=Sim.WAGE_OWE_CAP;
ok(Sim.joyOf(v)<j0||j0<=15,'gli arretrati tolgono felicità ('+j0+' → '+Sim.joyOf(v)+')');
h.owed=0;
console.log('4) salvataggio');
Sim.setTaxRate('high');
const snap=JSON.parse(JSON.stringify(Sim.exportState()));
Sim.importState(JSON.parse(JSON.stringify(snap)));ok(S.taxRate==='high','aliquota nel salvataggio');
const old=JSON.parse(JSON.stringify(snap));delete old.S.taxRate;delete old.S.ledger;
Sim.importState(old);ok(S.taxRate==='normal'&&Array.isArray(S.ledger.rows),'salvataggio vecchio: valori di riserva');
console.log(fails?('FALLITI '+fails):'TUTTO OK');process.exit(fails?1:0);
